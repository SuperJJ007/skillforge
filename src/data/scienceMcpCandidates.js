import {
  createSourceAuthor,
  createSourceCandidate,
  installationFact,
  sourceFact,
} from './sourceCandidateFactory.js';

const FETCHED_AT = '2026-08-13T09:15:00Z';

const makeMcp = ({
  slug,
  title,
  description,
  icon,
  tags,
  repositoryUrl,
  revision,
  revisionCommittedAt,
  rootPath = '',
  manifestPath,
  author,
  authorSlug,
  ownerUrl,
  ownerAvatarUrl,
  declaredVersion,
  license,
  licensePath,
  evidencePath,
  capabilities,
  installTitle,
  installDescription,
  installCommand,
  installEvidencePath,
  requirement,
  integration,
  caution,
}) => {
  const blob = `${repositoryUrl}/blob/${revision}`;
  const evidenceUrl = `${blob}/${evidencePath}`;
  return createSourceCandidate({
    slug,
    title,
    description,
    type: 'MCP',
    icon,
    author,
    authorSlug,
    tags,
    repositoryUrl,
    revision,
    revisionCommittedAt,
    fetchedAt: FETCHED_AT,
    rootPath,
    manifestPath,
    project: {
      declaredVersion,
      ownerUrl,
      ownerAvatarUrl,
      license: {
        spdx: license,
        name: license === 'NOASSERTION' ? '仓库未声明可识别许可证' : `${license} License`,
        evidenceUrl: `${blob}/${licensePath}`,
      },
      capabilities: capabilities.map(([factTitle, factDescription]) => (
        sourceFact(factTitle, factDescription, evidenceUrl)
      )),
      installationMethods: [installationFact(
        installTitle,
        installDescription,
        installCommand,
        `${blob}/${installEvidencePath}`,
      )],
      requirements: [sourceFact('运行前提', requirement, evidenceUrl)],
      integrations: [sourceFact('MCP 接入面', integration, evidenceUrl)],
      cautions: [sourceFact('使用边界', caution, evidenceUrl)],
    },
  });
};

